function klarifyLang() {
  return sessionStorage.getItem('klarify_lang') || 'de';
}

function t(key) {
  const lang = klarifyLang();
  const table = KLARIFY_I18N[lang] || KLARIFY_I18N.en;
  if (typeof table[key] === 'string') return table[key];
  if (typeof KLARIFY_I18N.en[key] === 'string') return KLARIFY_I18N.en[key];
  return key;
}

function applyRtl() {
  const lang = klarifyLang();
  const rtl = lang === 'ar' || lang === 'he' || lang === 'fa' || lang === 'ur';
  document.documentElement.dir = rtl ? 'rtl' : 'ltr';
  document.documentElement.lang = lang;
}

function greeting() {
  const h = new Date().getHours();
  const lang = klarifyLang();
  if (lang === 'de') {
    if (h < 12) return 'Guten Morgen.';
    if (h < 18) return 'Guten Tag.';
    return 'Guten Abend.';
  }
  return t('homeGreeting');
}
